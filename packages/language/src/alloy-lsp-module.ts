/**
 * Declaration of custom services - add your own service classes here.
 */
export type AlloyLspAddedServices = {
    references: {
        ModuleResolver: AlloyModuleResolver
    },
    typing: {
        TypeSystem: AlloyTypeSystem
    },
    analysis: {
        Analyzer: AlloyAnalyzer
    },
    validation: {
        AlloyLspValidator: AlloyLspValidator
    }
}

/**
 * Union of Langium default services and your custom services - use this as constructor parameter
 * of custom service classes.
 */
export type AlloyLspServices = LangiumServices & AlloyLspAddedServices

/**
 * Dependency injection module that overrides Langium default services and contributes the
 * declared custom services. The Langium defaults can be partially specified to override only
 * selected services, while the custom services must be fully specified.
 */
export const AlloyLspModule: Module<AlloyLspServices, PartialLangiumServices & AlloyLspAddedServices> = {
    parser: {
        ValueConverter: () => new AlloyLspValueConverter(),
        TokenBuilder: () => new AlloyTokenBuilder()
    },
    references: {
        ModuleResolver: (services) => new AlloyModuleResolver(services),
        ScopeComputation: (services) => new AlloyScopeComputation(services),
        ScopeProvider: (services) => new AlloyScopeProvider(services),
        Linker: (services) => new AlloyLinker(services)
    },
    typing: {
        TypeSystem: (services) => new AlloyTypeSystem(services)
    },
    analysis: {
        Analyzer: (services) => new AlloyAnalyzer(services)
    },
    lsp: {
        CompletionProvider: (services) => new AlloyCompletionProvider(services),
        DefinitionProvider: (services) => new AlloyDefinitionProvider(services),
        DocumentSymbolProvider: () => new AlloyDocumentSymbolProvider(),
        HoverProvider: (services) => new AlloyHoverProvider(services),
        CodeActionProvider: (services) => new AlloyCodeActionProvider(services),
        Formatter: () => new AlloyFormatter(),
        InlayHintProvider: (services) => new AlloyInlayHintProvider(services),
        RenameProvider: (services) => new AlloyRenameProvider(services),
        SemanticTokenProvider: (services) => new AlloySemanticTokenProvider(services),
        SignatureHelp: () => new AlloySignatureHelpProvider(),
        CodeLensProvider: (services) => new AlloyCodeLensProvider(services)
    },
    validation: {
        AlloyLspValidator: (services) => new AlloyLspValidator(services)
    }
};

/** Shared services: the workspace manager also loads the bundled util library. */
export const AlloyLspSharedModule: Module<LangiumSharedServices, PartialLangiumSharedServices> = {
    workspace: {
        WorkspaceManager: (services) => new AlloyWorkspaceManager(services)
    },
    lsp: {
        NodeKindProvider: () => new AlloyNodeKindProvider()
    }
};

/**
 * Create the full set of services required by Langium.
 *
 * First inject the shared services by merging two modules:
 *  - Langium default shared services
 *  - Services generated by langium-cli
 *
 * Then inject the language-specific services by merging three modules:
 *  - Langium default language-specific services
 *  - Services generated by langium-cli
 *  - Services specified in this file
 *
 * @param context Optional module context with the LSP connection
 * @returns An object wrapping the shared services and the language-specific services
 */
export function createAlloyLspServices(context: DefaultSharedModuleContext): {
    shared: LangiumSharedServices,
    AlloyLsp: AlloyLspServices
} {
    const shared = inject(
        createDefaultSharedModule(context),
        AlloyLspGeneratedSharedModule,
        AlloyLspSharedModule
    );
    const AlloyLsp = inject(
        createDefaultModule({ shared }),
        AlloyLspGeneratedModule,
        AlloyLspModule
    );
    shared.ServiceRegistry.register(AlloyLsp);
    registerValidationChecks(AlloyLsp);
    if (!context.connection) {
        // We don't run inside a language server
        // Therefore, initialize the configuration provider instantly
        shared.workspace.ConfigurationProvider.initialized({});
    }
    return { shared, AlloyLsp };
}
